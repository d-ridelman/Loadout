// Writes licenses/THIRD_PARTY_NOTICES.md: the Rust crates linked into the shipped programs (loadout.exe, loadout-ml.exe,
// context-toolkit.exe) with their licenses, from `cargo tree` (normal dependencies only: build and dev ones are not shipped).
// Run after a dependency change: node tools/notices.mjs. Electron and Chromium notices come with the installer (electron-builder).
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..')
const NL = String.fromCharCode(10)
const own = new Set(['loadoutd', 'loadout-ml', 'loadout-core', 'context-toolkit'])
// no-proc-macro: macros run at compile time and are not linked into the programs
const tree = execFileSync('cargo', ['tree', '-e', 'normal,no-proc-macro', '-p', 'loadoutd', '-p', 'loadout-ml', '-p', 'context-toolkit', '--prefix', 'none', '--format', '{p}|{l}'], { cwd: repo, encoding: 'utf8' })
const crates = [
  ...new Set(
    tree
      .split(NL)
      .map((l) => l.replace(' (*)', '').replace(' (proc-macro)', '').trim())
      .filter((l) => l.includes('|')),
  ),
]
  .map((l) => {
    const [pkg, license] = l.split('|')
    const [name, version] = pkg.split(' ')
    return { name, version, license: license || 'see the crate' }
  })
  .filter((c) => !own.has(c.name))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

// the license files each crate publishes (with its copyright lines), one copy of every distinct text
const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], { cwd: repo, encoding: 'utf8', maxBuffer: 64 << 20 }))
const dirOf = new Map(meta.packages.map((p) => [`${p.name} v${p.version}`, dirname(p.manifest_path)]))
const texts = new Map()
const bare = []
for (const c of crates) {
  const dir = dirOf.get(`${c.name} ${c.version}`)
  const files = dir ? readdirSync(dir, { withFileTypes: true }).filter((f) => f.isFile() && /^(licen[cs]e|copying|notice)/i.test(f.name)) : []
  if (files.length === 0) bare.push(`${c.name} ${c.version}`)
  for (const f of files) {
    const body = readFileSync(join(dir, f.name), 'utf8').replaceAll(String.fromCharCode(13), '').trim()
    const users = texts.get(body) ?? []
    texts.set(body, [...users, `${c.name} ${c.version} (${f.name})`])
  }
}
const licenseTexts = [...texts].flatMap(([body, users]) => ['', `### ${users.join(', ')}`, '', '```', body.replaceAll('```', "'''"), '```'])

const ortLicense = readFileSync(join(repo, 'licenses', 'onnxruntime-LICENSE.txt'), 'utf8').trim()
const text = [
  '# Third-party notices',
  '',
  'Loadout is MIT-licensed (see `LICENSE`). The installer also carries software of others under their licenses.',
  '',
  '## ONNX Runtime 1.31.0',
  '',
  '`loadout-ml.exe` links ONNX Runtime statically (the build of pyke.io that the `ort` crate downloads, sha256-checked).',
  'Its own third-party notices are in `onnxruntime-ThirdPartyNotices.txt` next to this file.',
  '',
  '```',
  ortLicense,
  '```',
  '',
  'It is built with DirectML and uses the DirectML, Direct3D 12 and DXGI libraries of Windows itself (System32); Loadout runs',
  'the model on the CPU.',
  '',
  '## Microsoft Visual C++ runtime',
  '',
  '`vcruntime140.dll`, `vcruntime140_1.dll`, `msvcp140.dll` and `msvcp140_1.dll` next to `loadout-ml.exe` are the',
  'redistributable files of the Visual C++ runtime (Visual Studio `VC\\Redist`), shipped app-locally so it starts without the',
  'Redistributable installed; they are covered by the Visual Studio license terms for distributable code. `loadout.exe` and',
  '`context-toolkit.exe` link the static vcruntime of the same toolset.',
  '',
  '## The model of "Similar skills"',
  '',
  '`sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2` (Apache-2.0) is not in the installer: it is downloaded from',
  'Hugging Face on a click.',
  '',
  '## Electron and Chromium',
  '',
  'Their notices are installed with the app: `LICENSE.electron.txt` and `LICENSES.chromium.html`.',
  '',
  '## Rust crates in loadout.exe, loadout-ml.exe and context-toolkit.exe',
  '',
  'Generated by `node tools/notices.mjs` from `cargo tree` (linked crates only); the license files the crates publish follow',
  'the table, one copy of each distinct text.',
  '',
  '| Crate | Version | License |',
  '|---|---|---|',
  ...crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} |`),
  '',
  '## License texts of the crates',
  ...licenseTexts,
  '',
  ...(bare.length ? ['Crates that publish no license file (their license is the SPDX id above): ' + bare.join(', ') + '.', ''] : []),
].join(NL)
writeFileSync(join(repo, 'licenses', 'THIRD_PARTY_NOTICES.md'), text)
console.log(`${crates.length} crates`)
